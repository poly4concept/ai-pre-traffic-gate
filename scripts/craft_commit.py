#!/usr/bin/env python3
"""Phase 2.5d -- manufacture commits with specific, controllable risk signals.

WHY THIS EXISTS

Change context is the one signal the gate cannot be handed synthetically. The
security and health signals can be manufactured by breaking the app (2.5a) or
tightening an alarm (2.5b), but "a 600-line Friday-night change to payments/"
is not a thing you can configure -- it has to be an actual commit, because the
whole path from `git log` through `build_change_context.py` through base64
through the SHA cross-check has to run for real.

That is the point. These commits are SYNTHETIC IN CONTENT and REAL IN FORM:

    real git objects, real SHAs, real committer timestamps
    real diff statistics computed by the real build script
    real CodePipeline source metadata
    a real cross-check between the two

Nothing here is a mock. A mock would prove the gate can read a dictionary; this
proves it can read a repository.

THE THREE SAFETY RULES, AND WHY EACH ONE

  1. EVERYTHING IS WRITTEN UNDER demo/synthetic/, AND NOTHING ELSE IS TOUCHED.
     A blast radius you can describe in one sentence is one you can also undo in
     one command. `cleanup` deletes exactly that directory.

  2. HISTORY IS NEVER REWRITTEN. No amend, no rebase, no force-push. Every
     operation adds a commit, including the teardown. A script that manufactures
     commits and can also rewrite history is one typo away from being the worst
     thing in the repository.

  3. PUSHING IS OPT-IN. A local commit is undone with `git reset`; a pushed one
     has started a pipeline and possibly a deployment. Those deserve different
     levels of deliberateness, so `--push` is a separate flag.

WHY THE PATHS SAY `demo/synthetic/payments/` RATHER THAN `payments/`

The honest choice, and it costs a little realism. A reviewer looking at the
audit record can see immediately that the change was manufactured, which matters
because these records are talk material -- a demo that is indistinguishable from
a real incident is a demo that can be misrepresented, including by me.

The signal still works: the sensitive-path check looks for `payments/` as a
substring, and it is there. What is lost is the pretence, which was never worth
having.
"""

from __future__ import annotations

import argparse
import os
import subprocess
import sys
from dataclasses import dataclass, field
from datetime import UTC, datetime, timedelta
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]

# The only directory this script will ever write to or delete.
SYNTHETIC_DIR = REPO_ROOT / "demo" / "synthetic"

_USE_COLOUR = sys.stdout.isatty() and not os.environ.get("NO_COLOR")


def _c(text: str, colour: str) -> str:
    if not _USE_COLOUR:
        return text
    codes = {"green": "32", "red": "31", "yellow": "33", "dim": "90", "bold": "1"}
    return f"\033[{codes[colour]}m{text}\033[0m"


@dataclass(frozen=True)
class Recipe:
    """One manufactured change, described by the signals it should produce."""

    name: str
    summary: str
    message: str
    # (relative path under demo/synthetic/, number of lines to write)
    files: tuple[tuple[str, int], ...]
    # Hours to subtract from now. Used to place the commit at a specific local
    # time of day -- see `_commit_timestamp`.
    weekday: int | None = None
    hour: int | None = None
    author: str | None = None
    expects: tuple[str, ...] = field(default_factory=tuple)


def _lines(path: str, count: int) -> str:
    """Filler that looks like the file type it is pretending to be.

    Deliberately inert in every case -- no imports that resolve, no syntax that
    would tempt anything to execute it. These files exist to be counted by
    `git diff --numstat`, not to run.
    """
    if path.endswith(".md"):
        body = "\n".join(f"- synthetic documentation line {i}" for i in range(count))
        return f"# Synthetic demo content\n\n{body}\n"
    body = "\n".join(f"    synthetic_value_{i} = {i}  # generated" for i in range(count))
    return (
        '"""Synthetic file generated by scripts/craft_commit.py.\n\n'
        "Not executed, not imported, not deployed. It exists so that a real\n"
        "commit has real diff statistics for the gate to read.\n"
        '"""\n\n\ndef synthetic() -> None:\n'
        f"{body}\n"
    )


