BY_NAME = {r.name: r for r in RECIPES}


def git(*args: str, check: bool = True, env: dict[str, str] | None = None) -> str:
    """Run a git command in the repository root.

    `shell=False` with an argument list, so a crafted commit message containing
    quotes, newlines or semicolons is passed as one argument and never reaches a
    shell. That is not incidental hygiene here: this script's entire job is
    generating hostile-looking commit messages, and one of the recipes is
    literally an injection payload.
    """
    merged = {**os.environ, **(env or {})}
    result = subprocess.run(  # noqa: S603 - fixed executable, argument list, no shell
        ["git", *args],  # noqa: S607 - git is expected on PATH for a git workflow
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        env=merged,
        check=False,
    )
    if check and result.returncode != 0:
        raise RuntimeError(f"git {' '.join(args)} failed: {result.stderr.strip()}")
    return result.stdout.strip()


def _commit_timestamp(recipe: Recipe) -> str:
    """The most recent past datetime matching the recipe's weekday and hour.

    Backdating is done through git's own author/committer date rather than by
    faking a field downstream, so `git log -1 --format=%cI` reports it, the
    build script picks it up, and `is_off_hours` is computed from a genuine
    timestamp. Every layer sees what it would see for a real 8pm Friday commit.

    Anchored to the recent past rather than a fixed date so that deploy-cadence
    signals stay plausible relative to it.
    """
    now = datetime.now(UTC)
    if recipe.weekday is None or recipe.hour is None:
        return now.isoformat()

    days_back = (now.weekday() - recipe.weekday) % 7
    if days_back == 0 and now.hour < recipe.hour:
        days_back = 7
    stamp = (now - timedelta(days=days_back)).replace(
        hour=recipe.hour, minute=42, second=0, microsecond=0
    )
    return stamp.isoformat()


def _assert_clean_tree() -> None:
    """Refuse to run on a dirty tree.

    Not fussiness. `cleanup` and `create` both commit whatever is staged under
    the synthetic directory, and a tree with unrelated work in progress makes it
    far too easy to sweep real changes into a commit labelled synthetic.
    """
    dirty = git("status", "--porcelain")
    if dirty:
        raise SystemExit(
            _c("Refusing to run: the working tree has uncommitted changes.\n", "red")
            + "Commit or stash them first. This script commits on your behalf, and\n"
            "mixing real work into a synthetic commit is not something it can undo.\n\n" + dirty
        )


def create(recipe: Recipe, *, push: bool, dry_run: bool) -> int:
    branch = git("rev-parse", "--abbrev-ref", "HEAD")
    stamp = _commit_timestamp(recipe)

    total_lines = sum(count for _, count in recipe.files)
    print(_c(f"\nRecipe: {recipe.name}", "bold"))
    print(f"  {recipe.summary}\n")
    print(f"  branch       {branch}")
    print(f"  files        {len(recipe.files)}")
    print(f"  lines        ~{total_lines}")
    print(f"  timestamp    {stamp}")
    print(f"  author       {recipe.author or '(your git identity)'}")
    print(f"  message      {recipe.message.splitlines()[0]}")
    if recipe.expects:
        print(f"  expect       {', '.join(recipe.expects)}")

    if dry_run:
        print(_c("\n  DRY RUN -- nothing written, nothing committed.", "yellow"))
        return 0

    _assert_clean_tree()

    # Written fresh each time, so re-running a recipe produces a real diff
    # against the previous run rather than an empty commit.
    marker = datetime.now(UTC).strftime("%Y%m%d%H%M%S")
    for rel, count in recipe.files:
        path = SYNTHETIC_DIR / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(f"# run {marker}\n" + _lines(rel, count), encoding="utf-8")

    git("add", "--", str(SYNTHETIC_DIR.relative_to(REPO_ROOT)))

    env = {"GIT_COMMITTER_DATE": stamp, "GIT_AUTHOR_DATE": stamp}
    args = ["commit", "-m", recipe.message]
    if recipe.author:
        args += ["--author", recipe.author]
    git(*args, env=env)

    sha = git("rev-parse", "HEAD")
    print(_c(f"\n  committed {sha[:12]} on {branch}", "green"))

    if push:
        git("push", "origin", branch)
        print(_c(f"  pushed to origin/{branch} -- the pipeline will start shortly", "green"))
    else:
        print(_c("  NOT pushed.", "yellow"))
        print(f"    push it:  git push origin {branch}")
        print("    undo it:  git reset --hard HEAD~1   (safe: not pushed yet)")

    return 0


def cleanup(*, push: bool, dry_run: bool) -> int:
    """THE TEARDOWN. Removes the synthetic directory and commits the removal."""
    if not SYNTHETIC_DIR.exists():
        print(_c("Nothing to clean: demo/synthetic/ does not exist.", "dim"))
        return 0

    files = sorted(p for p in SYNTHETIC_DIR.rglob("*") if p.is_file())
    print(_c(f"\nRemoving {len(files)} synthetic file(s) under demo/synthetic/", "bold"))

    if dry_run:
        for p in files[:10]:
            print(f"  {p.relative_to(REPO_ROOT)}")
        if len(files) > 10:
            print(f"  ... and {len(files) - 10} more")
        print(_c("\n  DRY RUN -- nothing removed.", "yellow"))
        return 0

    _assert_clean_tree()

    # `git rm -r` rather than deleting from disk, so the removal is staged and
    # the commit is a normal, revertible commit -- not a history rewrite.
    git("rm", "-r", "--quiet", "--", str(SYNTHETIC_DIR.relative_to(REPO_ROOT)))
    git("commit", "-m", "Remove synthetic demo commits (Phase 2.5d teardown)")

    branch = git("rev-parse", "--abbrev-ref", "HEAD")
    print(_c(f"  removed and committed on {branch}", "green"))
    if push:
        git("push", "origin", branch)
        print(_c(f"  pushed to origin/{branch}", "green"))
    return 0


def list_recipes() -> int:
    print(_c("\nAvailable recipes", "bold"))
    for r in RECIPES:
        total = sum(c for _, c in r.files)
        print(f"\n  {_c(r.name, 'bold')}")
        print(f"    {r.summary}")
        print(f"    {len(r.files)} file(s), ~{total} lines")
        if r.expects:
            print(f"    expect: {', '.join(r.expects)}")
    print()
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)

    sub.add_parser("list", help="show the available recipes")

    create_cmd = sub.add_parser("create", help="write files and make one commit")
    create_cmd.add_argument("recipe", choices=sorted(BY_NAME))
    create_cmd.add_argument(
        "--push",
        action="store_true",
        help="push afterwards, which starts the pipeline (opt-in on purpose)",
    )

    clean_cmd = sub.add_parser("cleanup", help="remove demo/synthetic/ (THE TEARDOWN)")
    clean_cmd.add_argument("--push", action="store_true")

    for p in (create_cmd, clean_cmd):
        p.add_argument("--dry-run", action="store_true", help="describe, change nothing")

    args = parser.parse_args()

    try:
        if args.command == "list":
            return list_recipes()
        if args.command == "create":
            return create(BY_NAME[args.recipe], push=args.push, dry_run=args.dry_run)
        if args.command == "cleanup":
            return cleanup(push=args.push, dry_run=args.dry_run)
    except RuntimeError as exc:
        print(_c(f"\n{exc}", "red"))
        return 1

    return 0


if __name__ == "__main__":
    sys.exit(main())
